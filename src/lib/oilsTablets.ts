export function getOilTablet(slug: string) {
  return oilTabletEntries.find((e) => e.slug === slug);
}

export function searchOilTablets(query: string) {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return oilTabletEntries.filter((e) => {
    const hay = [
      e.name,
      e.slug,
      ...e.alternativeNames,
      e.chemicalClass,
      e.category,
      OIL_TABLET_CATEGORY_LABELS[e.category],
      ...e.forms.map((f) => OIL_TABLET_FORM_LABELS[f]),
      ...e.cataloguePresentations,
      ...e.searchTerms,
    ]
      .join(" ")
      .toLowerCase();
    return hay.includes(q);
  });
}

export function oilTabletsByForm(form: OilTabletForm) {
  return [...oilTabletEntries.filter((e) => e.forms.includes(form))].sort((a, b) =>
    a.name.localeCompare(b.name),
  );
}

export function oilTabletsByCategory(category: OilTabletCategory) {
  return [...oilTabletEntries.filter((e) => e.category === category)].sort((a, b) =>
    a.name.localeCompare(b.name),
  );
}

export function oilTabletAzGroups() {
  const sorted = [...oilTabletEntries].sort((a, b) => a.name.localeCompare(b.name));
  const map = new Map<string, OilTabletEntry[]>();
  for (const e of sorted) {
    const letter = /[A-Z]/i.test(e.name[0]) ? e.name[0].toUpperCase() : "#";
    map.set(letter, [...(map.get(letter) ?? []), e]);
  }
  return [...map.entries()];
}
