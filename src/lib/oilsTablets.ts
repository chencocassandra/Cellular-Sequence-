function item(opts: {
  slug: string;
  name: string;
  aliases?: string[];
  forms: OilTabletForm[];
  category: OilTabletCategory;
  chemicalClass: string;
  presentations: string[];
  what: string;
  risks: string;
  reg: string;
  au: string;
  kind: "steroid" | "research" | "medicine" | "poison";
  terms?: string[];
  peptideHref?: string;
}): OilTabletEntry {
  const badges: RegulatoryBadge[] =
    opts.kind === "medicine"
      ? ["APPROVED_MEDICINE"]
      : opts.kind === "poison"
        ? ["NOT_APPROVED_FOR_HUMAN_USE"]
        : ["RESEARCH_ONLY", "NOT_APPROVED_FOR_HUMAN_USE"];
  return {
    slug: opts.slug,
    name: opts.name,
    alternativeNames: opts.aliases ?? [],
    forms: opts.forms,
    category: opts.category,
    chemicalClass: opts.chemicalClass,
    cataloguePresentations: opts.presentations,
    whatItIs: opts.what,
    risks: opts.risks,
    regulatoryStatus: opts.reg,
    australianRegulatoryStatus: opts.au,
    badges,
    searchTerms: opts.terms ?? [],
    peptideHref: opts.peptideHref,
  };
}

